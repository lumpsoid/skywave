#[cfg(test)]
mod tests {
    use std::collections::HashSet;

    use super::*;
    use crate::{limits, normalise_context_name};

    #[test]
    fn the_word_lists_hold_distinct_lowercase_words() {
        for list in [ADJECTIVES, NOUNS] {
            assert!(list.len() >= 200, "{} words", list.len());
            let distinct: HashSet<_> = list.iter().collect();
            assert_eq!(distinct.len(), list.len(), "a word is repeated");
            for word in list {
                assert!(!word.is_empty());
                assert!(
                    word.bytes().all(|b| b.is_ascii_lowercase()),
                    "{word:?} is not lowercase ASCII"
                );
            }
        }
        let adjectives: HashSet<_> = ADJECTIVES.iter().collect();
        assert!(NOUNS.iter().all(|noun| !adjectives.contains(noun)));
    }

    #[test]
    fn every_name_survives_normalising_and_fits_the_cap() {
        // The longest pair bounds every name the lists can make.
        let longest = |list: &[&str]| list.iter().map(|w| w.len()).max().unwrap();
        assert!(longest(ADJECTIVES) + 1 + longest(NOUNS) <= limits::CONTEXT_NAME_MAX_CHARS);
        let mut seen = HashSet::new();
        for _ in 0..200 {
            let name = random();
            assert_eq!(
                normalise_context_name(&name).as_deref(),
                Some(name.as_str())
            );
            let (adjective, noun) = name.split_once(' ').expect("two words");
            assert!(ADJECTIVES.contains(&adjective), "{name}");
            assert!(NOUNS.contains(&noun), "{name}");
            seen.insert(name);
        }
        // Random, not a constant: 200 draws from 62 500 pairs repeat little.
        assert!(seen.len() > 150, "only {} distinct names", seen.len());
    }
}
