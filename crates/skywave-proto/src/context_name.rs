//! Two-word names for session contexts ("velvet walrus").
//!
//! A name is carried in the log (`SessionCreated::context_name`,
//! `ContextStarted::name`), never computed from a context's id, so these
//! lists may change without renaming any context. The server names a
//! session's first context; a client names each context it clears.

use uuid::Uuid;

/// A random adjective and noun joined by a space. Always passes
/// [`normalise_context_name`](crate::normalise_context_name) unchanged.
///
/// The randomness is the random tail of a fresh UUIDv7: its last 32 bits
/// (the leading ones of its random part may be a counter).
pub fn random() -> String {
    let bytes = Uuid::now_v7().into_bytes();
    let adjective = usize::from(u16::from_be_bytes([bytes[12], bytes[13]]));
    let noun = usize::from(u16::from_be_bytes([bytes[14], bytes[15]]));
    format!(
        "{} {}",
        ADJECTIVES[adjective % ADJECTIVES.len()],
        NOUNS[noun % NOUNS.len()]
    )
}

